#define CDC_NPU_NATIVE_CFG_LAYER_OFFSET     0x00000A00u

#define CDC_NPU_NATIVE_CFG_ACT_BASE_ADDR    (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x80u)
