#define CDC_NPU_NATIVE_ACT_TIL_YSTEP        (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x3Cu)

#define CDC_NPU_NATIVE_NCONTEXTS            (CDC_NPU_NATIVE_CFG_OUT_OFFSET + 0x00u)
#define CDC_NPU_NATIVE_TIL_CYLIM            (CDC_NPU_NATIVE_CFG_OUT_OFFSET + 0x14u)
