#define CDC_NPU_NATIVE_WEI_COLS_ACTIVE      (CDC_NPU_NATIVE_CFG_WEI_OFFSET + 0x28u)
#define CDC_NPU_NATIVE_WEI_WALIGNED         (CDC_NPU_NATIVE_CFG_WEI_OFFSET + 0x2Cu)

#define CDC_NPU_NATIVE_ACT_XLIM             (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x14u)
#define CDC_NPU_NATIVE_ACT_XSTEP            (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x18u)
#define CDC_NPU_NATIVE_ACT_YLIM             (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x1Cu)
#define CDC_NPU_NATIVE_ACT_YSTEP            (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x20u)
#define CDC_NPU_NATIVE_ACT_CHLIM            (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x24u)
#define CDC_NPU_NATIVE_ACT_CHSTEP           (CDC_NPU_NATIVE_CFG_ACT_OFFSET + 0x2Cu)
