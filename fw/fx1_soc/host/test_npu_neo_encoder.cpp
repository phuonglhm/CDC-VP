// Host test: the firmware's neo_lite encoder (fw/fx1_soc/drivers/fx1_npu_build.c,
// C) against the SAURIA v4.7 drop's C++ (has/has_host_neo.h plan() and
// decode_regs(), read in place, never modified):
//   - MAX_POOL / AVG_POOL / ADD-as-RESIDUAL: all 82 words equal for a sweep
//     of shapes and parameters; MAX_POOL and RESIDUAL are "as given" for the
//     strict hardware (no A-* / B-* issue), AVG_POOL carries A-H3 (refused);
//   - what the C encoder declines (pooling padding, n not a multiple of 32,
//     per-operand shifts that do not reduce) is not "as given" in the drop;
//   - the GEMM_FUSED word table of the firmware DFC test
//     (tests/npu_common/npu_neo_gemm_words.h) is what plan() encodes, decodes
//     without error, and carries A-H1 (strict refusal by a hardware gap, not
//     an inconsistent image).
//   test_npu_neo_encoder               run the checks
//   test_npu_neo_encoder --emit-gemm   print npu_neo_gemm_words.h
#include <cstdio>
#include <cstring>
#include <string>

#include "has/has_host_neo.h"

extern "C" {
#include "fx1_npu.h"
#include "npu_neo_gemm_words.h"
}

namespace {

int failures = 0;
void check(bool ok, const std::string& what)
{
    if (!ok) {
        ++failures;
        std::printf("  [FAIL] %s\n", what.c_str());
    }
}

bool has_issue(const has::host_neo::Plan& p, const char* code)
{
    for (const auto& s : p.issues)
        if (s == code) return true;
    return false;
}

std::string words_diff(const neo::Image& im, const fx1_npu_neo_t& n)
{
    for (unsigned k = 0; k < FX1_NPU_NEO_REG_COUNT; ++k)
        if (im.reg[k] != n.word[k]) {
            char b[96];
            std::snprintf(b, sizeof b, "word %u: drop 0x%08x, firmware 0x%08x", k, im.reg[k], n.word[k]);
            return b;
        }
    return std::string();
}

has::LayerInstr pool_li(const fx1_npu_pool_t& p)
{
    has::LayerInstr li;
    li.opcode = 0x15;
    li.mode = p.avg ? 5 : 1;
    li.c = static_cast<int>(p.c);
    li.h = static_cast<int>(p.h);
    li.w = static_cast<int>(p.w);
    li.pool_k = static_cast<int>(p.k);
    li.pool_s = static_cast<int>(p.stride);
    li.pool_p = static_cast<int>(p.pad);
    li.a_addr = p.in;
    li.out_addr = p.out;
    if (p.avg) {
        li.avg_scale = static_cast<uint32_t>(p.so);
        li.avg_shift = p.sho;
    }
    return li;
}

has::LayerInstr add_li(const fx1_npu_add_t& a)
{
    has::LayerInstr li;
    li.opcode = 0x15;
    li.mode = 0;
    li.n = a.n;
    li.a_addr = a.a;
    li.b_addr = a.b;
    li.out_addr = a.out;
    li.add.zpA = a.zp_a;
    li.add.zpB = a.zp_b;
    li.add.zpO = a.zp_o;
    li.add.SA = static_cast<uint32_t>(a.sa);
    li.add.SB = static_cast<uint32_t>(a.sb);
    li.add.SO = static_cast<uint32_t>(a.so);
    li.add.sA = a.sha;
    li.add.sB = a.shb;
    li.add.sO = a.sho;
    return li;
}

// The GEMM_FUSED layer of the DFC refusal test: R1 of npu_cases.h at window
// offsets (the firmware adds the window base to the address words).
has::LayerInstr gemm_li()
{
    has::LayerInstr li;
    li.opcode = 0x12;
    li.in_addr = 0x0400;
    li.w_addr = 0x0500;
    li.out_addr = 0x0700;
    li.bias_addr = 0x0640;
    li.in_c = 4;
    li.in_h = 8;
    li.in_w = 8;
    li.cin_t = 4;
    li.geom.cout = 8;
    li.geom.oh = 8;
    li.geom.ow = 8;
    li.geom.kh = li.geom.kw = 3;
    li.geom.pad_t = li.geom.pad_l = li.geom.pad_b = li.geom.pad_r = 1;
    li.geom.cout_t = 8;
    li.geom.h_t = 8;
    li.geom.w_t = 8;
    li.per_channel = true;
    li.scale_addr = 0x0680;
    li.shift_addr = 0x06C0;
    li.act = 1;
    li.zp_out = 3;
    return li;
}

int emit_gemm()
{
    const has::host_neo::Plan p = has::host_neo::plan(gemm_li());
    std::printf("/* Generated by test_npu_neo_encoder --emit-gemm from the SAURIA v4.7 drop's\n"
                " * has/has_host_neo.h plan(): the 82 neo_lite words of GEMM_FUSED conv 3x3,\n"
                " * [4][8][8] -> [8][8][8], pad 1, ReLU, per-channel requant, with window\n"
                " * offsets in the address words (START_A/B/C = 18/19/20, START_SB = 34). The\n"
                " * strict hardware refuses it (A-H1). Checked by fx1_fw_npu_neo_encoder. */\n"
                "#ifndef NPU_NEO_GEMM_WORDS_H\n#define NPU_NEO_GEMM_WORDS_H\n\n#include <stdint.h>\n\n"
                "static const uint32_t npu_neo_gemm_words[82] = {\n");
    for (unsigned k = 0; k < 82; ++k) std::printf("%s0x%08xu,%s", k % 6 == 0 ? "    " : " ", p.img.reg[k], k % 6 == 5 || k == 81 ? "\n" : "");
    std::printf("};\nstatic const unsigned npu_neo_gemm_addr_words[4] = {18, 19, 20, 34};\n\n#endif\n");
    return 0;
}

} // namespace

int main(int argc, char** argv)
{
    if (argc > 1 && std::strcmp(argv[1], "--emit-gemm") == 0) return emit_gemm();
    unsigned pools = 0, adds = 0, declined = 0;
    // Pooling sweep.
    for (unsigned c : {1u, 3u, 16u, 40u, 64u})
        for (unsigned h : {4u, 12u, 31u, 32u, 33u, 70u})
            for (unsigned w : {5u, 12u, 32u, 40u, 64u})
                for (unsigned k : {2u, 3u, 4u, 5u})
                    for (unsigned s : {1u, 2u, 3u})
                        for (int avg : {0, 1})
                            for (unsigned pad : {0u, 1u}) {
                                if (h + 2 * pad < k || w + 2 * pad < k) continue;
                                const fx1_npu_pool_t p{0x80901000u, 0x80980000u, c, h, w, k, pad, s, avg, 1, 2};
                                fx1_npu_neo_t n;
                                const int ok = fx1_npu_neo_pool(&n, &p);
                                has::LayerInstr li = pool_li(p);
                                const has::host_neo::Plan pl = has::host_neo::plan(li);
                                char what[128];
                                std::snprintf(what, sizeof what, "%s c%u h%u w%u k%u s%u p%u", avg ? "AVG" : "MAX", c, h, w, k, s, pad);
                                if (!ok) {
                                    ++declined;
                                    check(!pl.as_given(), std::string(what) + ": declined by the firmware but as given in the drop");
                                    continue;
                                }
                                ++pools;
                                check(pl.error.empty(), std::string(what) + ": drop error " + pl.error);
                                const std::string d = words_diff(pl.img, n);
                                check(d.empty(), std::string(what) + ": " + d);
                                if (avg)
                                    check(has_issue(pl, "A-H3"), std::string(what) + ": AVG_POOL without A-H3");
                                else
                                    check(pl.as_given(), std::string(what) + ": MAX_POOL not as given for the strict hardware");
                                const has::host_neo::Decoded dec = has::host_neo::decode_regs(pl.img);
                                check(dec.errors.empty(), std::string(what) + ": words do not decode");
                            }
    // ADD as RESIDUAL sweep.
    const struct {
        int zpa, zpb, zpo, sa, sha, sb, shb, so, sho;
    } q[] = {{3, -5, 2, 3000, 0, 5000, 0, 1, 14},   {0, 0, 0, 1, 0, 1, 0, 1, 0},     {-128, 127, -128, 4000000, 0, 1, 0, 1, 30},
             {7, 9, -3, 12000, 4, 9000, 3, 3, 12}, {1, -2, 3, 1 << 10, 10, 1 << 9, 9, 6, 13}, {5, 5, 5, 300, 2, 7, 0, 1, 8},
             {0, 0, 1, 100, 0, 200, 0, 1 << 4, 10}, {-1, 1, 0, 65536, 0, 65536, 0, 3, 20}, {2, 3, 4, 5, 1, 5, 0, 1, 3}};
    for (const auto& x : q)
        for (unsigned n : {32u, 64u, 96u, 576u, 1024u, 25600u, 100u}) {
            const fx1_npu_add_t a{0x80901000u, 0x80930000u, 0x80960000u, n, x.zpa, x.zpb, x.zpo, x.sa, x.sha, x.sb, x.shb, x.so, x.sho};
            fx1_npu_neo_t nn;
            const int ok = fx1_npu_neo_residual(&nn, &a);
            const has::host_neo::Plan pl = has::host_neo::plan(add_li(a));
            char what[160];
            std::snprintf(what, sizeof what, "ADD n%u zp %d %d %d S %d>>%d %d>>%d %d>>%d", n, x.zpa, x.zpb, x.zpo, x.sa, x.sha, x.sb,
                          x.shb, x.so, x.sho);
            if (!ok) {
                ++declined;
                check(!pl.as_given(), std::string(what) + ": declined by the firmware but as given in the drop");
                continue;
            }
            ++adds;
            const std::string d = words_diff(pl.img, nn);
            check(d.empty(), std::string(what) + ": " + d);
            check(pl.as_given(), std::string(what) + ": RESIDUAL not as given for the strict hardware");
            check(has::host_neo::decode_regs(pl.img).errors.empty(), std::string(what) + ": words do not decode");
        }
    // GEMM_FUSED table of the DFC refusal test.
    const has::host_neo::Plan g = has::host_neo::plan(gemm_li());
    bool same = true;
    for (unsigned k = 0; k < 82; ++k) same &= g.img.reg[k] == npu_neo_gemm_words[k];
    check(same, "npu_neo_gemm_words.h differs from plan(): regenerate with --emit-gemm");
    check(g.error.empty() && has::host_neo::decode_regs(g.img).errors.empty(), "GEMM words decode without error");
    check(has_issue(g, "A-H1"), "GEMM_FUSED carries A-H1 (strict refusal by a hardware gap)");
    for (unsigned k = 0; k < 4; ++k) check(npu_neo_gemm_words[npu_neo_gemm_addr_words[k]] != 0, "GEMM address word set");

    std::printf("[neo-encoder] pooling %u, residual %u compared word for word; %u declined by both; GEMM table %s\n", pools, adds,
                declined, same ? "matches" : "DIFFERS");
    std::printf("RESULT %s (%d failure%s)\n", failures ? "FAIL" : "PASS", failures, failures == 1 ? "" : "s");
    return failures ? 1 : 0;
}
