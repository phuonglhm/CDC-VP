#!/usr/bin/python3 -I
"""Generate src/fu3_iopad_map.h from the Common Spec v2.1 workbook, sheet
"IOPAD MAP" (decision Q06-a: die pads 1-108 are the pad identifiers).

    tools/gen_iopad_map.py FTEL_FU3_Common_Spec_v2.1.xlsx > src/fu3_iopad_map.h

Columns used: die pin number, PIN name, type, default (fixed) function, the
four csr_io_cfg[1:0] mux functions b00-b11 and the IOSEL group. "-" or an empty
cell is no function. The test-mode columns are all empty in v2.1.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main",
      "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships"}


def sheet_rows(path, wanted):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
            shared.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
    wb = ET.fromstring(z.read("xl/workbook.xml"))
    rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
    target = {r.get("Id"): r.get("Target") for r in rels}
    for sh in wb.find("m:sheets", NS):
        if sh.get("name") != wanted:
            continue
        root = ET.fromstring(z.read("xl/" + target[sh.get("{%s}id" % NS["r"])].replace("xl/", "").lstrip("/")))
        for row in root.iter("{%s}row" % NS["m"]):
            cells = {}
            for c in row.findall("m:c", NS):
                v = c.find("m:v", NS)
                if v is None:
                    continue
                col = 0
                for ch in re.match(r"[A-Z]+", c.get("r")).group(0):
                    col = col * 26 + ord(ch) - 64
                cells[col - 1] = shared[int(v.text)] if c.get("t") == "s" else v.text
            yield [cells.get(i, "").strip() for i in range(max(cells) + 1)] if cells else []
        return
    raise SystemExit("sheet not found: " + wanted)


def cstr(text):
    return "nullptr" if text in ("", "-") else '"%s"' % text


def main():
    pads = []
    for cells in sheet_rows(sys.argv[1], "IOPAD MAP"):
        if len(cells) < 13 or not re.fullmatch(r"\d+", cells[0]):
            continue
        die, _, _, pin, kind, fixed = cells[0:6]
        mux = cells[8:12]
        iosel = cells[12] if len(cells) > 12 else ""
        pads.append((int(die), pin, kind, fixed, mux, iosel))
    if [p[0] for p in pads] != list(range(1, 109)):
        raise SystemExit("IOPAD MAP: expected die pads 1-108 in order")
    out = ["#pragma once",
           "// Generated by tools/gen_iopad_map.py from FTEL_FU3_Common_Spec_v2.1.xlsx,",
           "// sheet \"IOPAD MAP\" (decision Q06-a: die pads 1-108). Do not edit by hand.",
           "// mux[s] is the function selected by csr_io_cfg[1:0] = s (nullptr: none);",
           "// a pad without mux functions carries its fixed function.",
           "",
           "namespace cdc::platforms::fu3_soc::iopad {",
           "",
           "struct die_pad {",
           "    unsigned die;",
           "    const char* pin;     // package pin name (nullptr: none)",
           "    const char* type;    // DIG, ANA, Source, Ground",
           "    const char* fixed;   // default / fixed function",
           "    const char* mux[4];  // csr_io_cfg[1:0] = b00, b01, b10, b11",
           "    int iosel;           // IOSEL_0 / IOSEL_1, -1: none",
           "};",
           "",
           "constexpr unsigned kDiePads = 108;",
           "constexpr die_pad kDiePad[kDiePads] = {"]
    for die, pin, kind, fixed, mux, iosel in pads:
        out.append("    {%d, %s, %s, %s, {%s}, %s}," % (
            die, cstr(pin), cstr(kind), cstr(fixed), ", ".join(cstr(m) for m in mux),
            iosel if iosel in ("0", "1") else "-1"))
    out += ["};", "", "} // namespace cdc::platforms::fu3_soc::iopad", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
