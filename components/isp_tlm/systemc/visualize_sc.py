#!/usr/bin/env python3
"""
Visualize YUV420 output of the SystemC ISP testbenches.

Mirrors the look-and-feel of the original `components/isp_tlm/visualize.py`
but is tuned for the SystemC streaming pipeline:
  - reads the two .yuv files generated by `tb_d65_pipeline`
    (`d65_pipeline.yuv` from SystemC, `d65_pipeline_golden.yuv` from C++)
  - accepts explicit `--input`, `--golden`, `--width`, `--height`
    arguments so you can reuse it for any future SystemC test
  - supports both planar YUV420 (Y..U..V) and NV12 (Y..UV..)
  - plots 3 panels: raw input (Bayer-coded) | golden | SystemC output
  - reports per-plane MSE between SystemC and golden

Usage:
  ./visualize.py                                    # default D65 outputs
  ./visualize.py --input <raw> --width 2688 --height 1520 \
                 --sc    path/to/d65_pipeline.yuv \
                 --golden path/to/d65_pipeline_golden.yuv \
                 --bit-depth 16 --pattern RGGB
"""

