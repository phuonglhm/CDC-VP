        uint32_t staging_base() const { return staging_base_; }
        void set_dram_base(uint32_t b) { dram_base_ = b; }
        uint32_t dram_base() const { return dram_base_; }

        size_t has_pending() const { return rtl->mmio.queued() + (rtl->mmio.executing() ? 1 : 0); }
        size_t native_queue_a() const { return native->decoder_inst ? native->decoder_inst->get_queue_a_size() : 0; }
        size_t native_queue_b() const { return native->decoder_inst ? native->decoder_inst->get_queue_b_size() : 0; }
        int native_state_a() const { return native->decoder_inst ? native->decoder_inst->get_state_a() : 0; }
        int native_state_b() const { return native->decoder_inst ? native->decoder_inst->get_state_b() : 0; }

    private:
        static constexpr uint32_t PARAM_LO = 0x40000400, PARAM_HI = 0x40000468;   // inclusive
        static constexpr uint32_t EXT_LO = 0x4000046C, EXT_END = 0x40000504;      // exclusive end
        static constexpr uint32_t PUSH_A = 0x40000310, STATUS = 0x40000318, RETIRED = 0x4000031C;
        static constexpr uint32_t kParamRegs = (PARAM_HI - PARAM_LO) / 4 + 1, kExtRegs = (EXT_END - EXT_LO) / 4;
        // Extension registers that hold DRAM addresses (scale, shift, LUT, parameter block, mask).
        static bool ext_is_address(uint32_t a)
        {
            return a == 0x40000490 || a == 0x40000494 || a == 0x40000498 || a == 0x400004E0 || a == 0x400004E4;
        }
        static bool param_is_address(uint32_t a)
        {
            return a == 0x40000400 || a == 0x40000404 || a == 0x40000408 || a == 0x4000040C || a == 0x40000434 || a == 0x40000444 ||
                   a == 0x40000448 || a == 0x4000044C;
        }
        // Words of the neo_lite register file that hold DRAM addresses (A, B, C, sbank, vbank0..2 starts): indices 18, 19, 20, 34, 35, 36, 37 from window offset 0x10.
        static bool neo_is_address_word(uint32_t a)
        {
            const uint32_t i = (a - has::NeoPort::BASE - 0x10u) / 4u;
            return a >= has::NeoPort::BASE + 0x10u && (a - has::NeoPort::BASE) % 4u == 0 && (i == 18 || i == 19 || i == 20 || (i >= 34 && i <= 37));
        }
        static bool is_ext(uint32_t a) { return a >= EXT_LO && a < EXT_END; }
        static bool is_param(uint32_t a) { return a >= PARAM_LO && a <= PARAM_HI; }
        static bool is_rtl_status(uint32_t a) { return a == STATUS || a == RETIRED; }

        void route()
        {
            const uint32_t a = i_host_addr.read();
            const bool w = i_host_wren.read(), r = i_host_rden.read();
            // DMA_TENSOR (0x16) has no extension register and no native counterpart: HasNpuTop when it accepts the opcode
            // HAS_HOST=neo: the window of the neo_lite register file and the doorbell (push of opcode 0x17) belong to HasNpuTop too
            const bool neo_win = rtl->neo.owns(a);
            const bool neo_bell = rtl->neo.on() && a == PUSH_A && w && (static_cast<uint32_t>(i_host_wdata.read()[0]) & 0xFFu) == has::NeoPort::BELL;
            const bool to_rtl_push = a == PUSH_A && (ext_seen_.read() || neo_bell || (rtl->mmio.dma_tensor && w && (static_cast<uint32_t>(i_host_wdata.read()[0]) & 0xFFu) == 0x16u));
            const bool rtl_only = is_ext(a) || is_rtl_status(a) || to_rtl_push || neo_win;
            n_addr_.write(a);
            n_wren_.write(w && !rtl_only);
            n_rden_.write(r && !rtl_only);
            h_addr_.write(a);
            h_wren_.write(w && (rtl_only || is_param(a)));
            h_rden_.write(r && (is_rtl_status(a) || neo_win));
            host_data_t d = i_host_wdata.read();
            if (w && (ext_is_address(a) || (neo_win && neo_is_address_word(a))))
            {
                const uint32_t v = static_cast<uint32_t>(d[0]);
                if (v >= dram_base_) d[0] = static_cast<double>(v - dram_base_);
            }
            h_wdata_.write(d);
        }
        void read_mux()
        {
            o_host_rdata.write((is_rtl_status(i_host_addr.read()) || rtl->neo.owns(i_host_addr.read())) ? h_rdata_.read() : n_rdata_.read());
        }
        void on_clock()
        {
            // Clock period for HasNpuTop's cycle accounting: the shortest distance between two rising edges (a gated
            // clock only adds longer gaps).
            const sc_time now = sc_time_stamp();
            if (have_edge_)
            {
                const sc_time d = now - last_edge_;
                if (d > SC_ZERO_TIME && (period_ == SC_ZERO_TIME || d < period_))
                {
                    period_ = d;
                    rtl->set_clock_period(period_);
                }
            }
            last_edge_ = now;
            have_edge_ = true;
            add_rtl_counters();
            if (rep_csv_) rep_tick();
            if (!i_rstn.read()) { ext_seen_.write(false); return; }
            if (i_host_wren.read())
            {
                const uint32_t a = i_host_addr.read();
                if (!rec_dir_.empty()) rec_write(a);
                if (h_wren_.read()) rep_write(a, static_cast<uint32_t>(h_wdata_.read()[0]));
                if (a == PUSH_A && h_wren_.read()) { last_opcode_ = static_cast<uint32_t>(h_wdata_.read()[0]) & 0xFFu; pushes_++; }
                if (is_ext(a)) ext_seen_.write(true);
                else if (a == PUSH_A) ext_seen_.write(false);
            }
            check_push();
            idle_prev_ = has_pending() == 0;
        }

        // ---- warnings (SAURIA_CORE_RTL_WARN) ----------------------------------------------------------------------------
        struct ErrSnap
        {
            uint64_t push{0}, fscale{0}, dtile{0};                                   // instruction decoder
            uint64_t framing{0}, wide{0}, deadlock{0}, param{0}, cfg{0}, lut{0}, oot{0};   // run
        };
        ErrSnap err_snap() const
        {
            ErrSnap e;
            e.push = rtl->mmio.n_errors; e.fscale = rtl->mmio.n_float_scale; e.dtile = rtl->mmio.n_default_tiling;
            e.framing = rtl->st.framing_errors; e.wide = rtl->st.wide_weight_rejected; e.deadlock = rtl->st.core_deadlocks;
            e.param = rtl->st.rce_param_errors; e.cfg = rtl->obp_block().cfg_errors; e.lut = rtl->obp_block().lut_lane_mismatch;
            e.oot = rtl->inline_out_of_tile;
            return e;
        }
        static const char *err_name(int c)
        {
            static const char *n[] = {"none", "Q_OVF", "LANE_B", "LEGACY64", "UNSUPPORTED_OP", "UNSUPPORTED_MODE", "BROADCAST",
                                      "NEED_LUT", "BAD_GEOM", "SCALE_RANGE", "NO_TILING", "SWEEP"};
            return (c >= 0 && c <= 11) ? n[c] : "?";
        }
        // Decoder counters move at the push; they are looked at on every clock (the push is decoded on a clock edge whose
        // order against this method is not defined).
        void check_push()
        {
            const uint64_t pe = rtl->mmio.n_errors, fs = rtl->mmio.n_float_scale, dt = rtl->mmio.n_default_tiling;
            if (pe == err_.push && fs == err_.fscale && dt == err_.dtile) return;
            if (warn_)
            {
                if (pe != err_.push)
                    std::fprintf(stderr, "[core_rtl] WARNING: push %llu (opcode 0x%02x) refused by HasNpuTop: error %d %s. The instruction "
                                 "does not run; read STATUS (0x40000318) bit 2 and bits 31..16, write it to clear\n",
                                 static_cast<unsigned long long>(pushes_), last_opcode_, static_cast<int>(rtl->mmio.last_error()),
                                 err_name(static_cast<int>(rtl->mmio.last_error())));
                if (fs != err_.fscale)
                    std::fprintf(stderr, "[core_rtl] WARNING: push %llu (opcode 0x%02x): no integer scale registers written, the scales "
                                 "were converted from the real-valued registers (approximation)\n",
                                 static_cast<unsigned long long>(pushes_), last_opcode_);
                if (dt != err_.dtile)
                    std::fprintf(stderr, "[core_rtl] WARNING: push %llu (opcode 0x%02x): no geometry / tile registers written, a default "
                                 "tiling was chosen\n", static_cast<unsigned long long>(pushes_), last_opcode_);
            }
            if (rep_csv_ && pe != err_.push)
            {
                if (!rep_q_.empty()) rep_q_.pop_back();   // the refused push never retires
                rep_refused_++;
                rep_summary();
            }
            if (rec_csv_ && pe != err_.push)
                std::fprintf(rec_csv_, "refused,%llu,0x%02x,%s\n", static_cast<unsigned long long>(pushes_), last_opcode_,
                             err_name(static_cast<int>(rtl->mmio.last_error())));
            err_.push = pe; err_.fscale = fs; err_.dtile = dt;
        }
        // Called when HasNpuTop retired an instruction (cycles = its cycles).
        void on_retire(uint64_t retired, uint64_t cycles)
        {
            const ErrSnap e = err_snap();
            const bool bad = e.framing != err_.framing || e.wide != err_.wide || e.deadlock != err_.deadlock || e.param != err_.param ||
                             e.cfg != err_.cfg || e.lut != err_.lut || e.oot != err_.oot;
            if (bad && warn_)
                std::fprintf(stderr, "[core_rtl] WARNING: instruction %llu retired with internal errors (its output may be missing or wrong): "
                             "framing +%llu, weights of a tile too large +%llu, core pass not finished +%llu, parameter block +%llu, "
                             "epilogue configuration +%llu, activation table lanes differ +%llu, epilogue lanes outside the tile +%llu\n",
                             static_cast<unsigned long long>(retired), static_cast<unsigned long long>(e.framing - err_.framing),
                             static_cast<unsigned long long>(e.wide - err_.wide), static_cast<unsigned long long>(e.deadlock - err_.deadlock),
                             static_cast<unsigned long long>(e.param - err_.param), static_cast<unsigned long long>(e.cfg - err_.cfg),
                             static_cast<unsigned long long>(e.lut - err_.lut), static_cast<unsigned long long>(e.oot - err_.oot));
            if (bad) rep_bad_ = true;
            if (rec_csv_)
            {
                std::fprintf(rec_csv_, "retired,%llu,%d,%llu,%s\n", static_cast<unsigned long long>(retired), rec_seg_,
                             static_cast<unsigned long long>(cycles), bad ? "errors" : "ok");
                std::fflush(rec_csv_);
            }
            err_.framing = e.framing; err_.wide = e.wide; err_.deadlock = e.deadlock; err_.param = e.param; err_.cfg = e.cfg;
            err_.lut = e.lut; err_.oot = e.oot;
            if (!rec_dir_.empty() && rec_seg_ >= 0)
            {
                rec_hash_ = image_hash();
                rec_hash_valid_ = true;
                if (has_pending() == 0) { write_image(seg_path("dram_golden.bin")); pad_init(); }
            }
        }

        // ---- recorder (SAURIA_CORE_RTL_RECORD) --------------------------------------------------------------------------
        static void make_dir(const std::string &d)
        {
#ifdef _WIN32
            _mkdir(d.c_str());
#else
            mkdir(d.c_str(), 0755);
#endif
        }
        size_t image_bytes() const { return dram_ ? std::min<size_t>(dram_->size(), staging_base_) : 0; }
        uint64_t image_hash() const
        {
            uint64_t h = 1469598103934665603ull;
            const size_t n = image_bytes();
            const uint8_t *p = n ? dram_->data() : nullptr;
            size_t i = 0;
            for (; i + 8 <= n; i += 8) { uint64_t w; std::memcpy(&w, p + i, 8); h = (h ^ w) * 1099511628211ull; }
            for (; i < n; i++) h = (h ^ p[i]) * 1099511628211ull;
            return h;
        }
        std::string seg_path(const char *file) const
        {
            char b[32];
            std::snprintf(b, sizeof b, "/seg%03d/", rec_seg_);
            return rec_dir_ + b + file;
        }
        // Bytes of the image that are recorded: up to the last non-zero byte and to the highest address written to an
        // address register, rounded up to 64 KiB; it never shrinks during a run.
        size_t image_extent()
        {
            const size_t n = image_bytes();
            const uint8_t *p = n ? dram_->data() : nullptr;
            size_t e = n;
            while (e >= 8) { uint64_t w; std::memcpy(&w, p + e - 8, 8); if (w) break; e -= 8; }
            e = std::max<size_t>(e, size_t(rec_max_addr_) + 1);
            e = std::min<size_t>((e + 65535) & ~size_t(65535), n);
            if (e > rec_extent_) rec_extent_ = e;
            return rec_extent_;
        }
        void write_image(const std::string &path)
        {
            const size_t n = image_extent();
            if (std::FILE *f = std::fopen(path.c_str(), "wb"))
            {
                if (n) std::fwrite(dram_->data(), 1, n, f);
                std::fclose(f);
            }
        }
        // dram_init.bin of the segment keeps the size of dram_golden.bin (zeros appended when the image grew).
        void pad_init()
        {
            if (rec_extent_ <= rec_init_bytes_) return;
            if (std::FILE *f = std::fopen(seg_path("dram_init.bin").c_str(), "ab"))
            {
                const std::vector<uint8_t> z(65536, 0);
                for (size_t left = rec_extent_ - rec_init_bytes_; left;) { const size_t k = std::min(left, z.size()); std::fwrite(z.data(), 1, k, f); left -= k; }
                std::fclose(f);
                rec_init_bytes_ = rec_extent_;
            }
        }
        void rec_close()
        {
            if (rec_mmio_) { std::fclose(rec_mmio_); rec_mmio_ = nullptr; }
            if (rec_csv_) { std::fclose(rec_csv_); rec_csv_ = nullptr; }
        }
        // One host write, as HasNpuTop sees it on this clock edge. The writes of an instruction are held until its push,
        // where the segment is decided.
        void rec_write(uint32_t a)
        {
            const uint32_t v = static_cast<uint32_t>(h_wdata_.read()[0]);
            char line[128];
            if (a == PUSH_A && !h_wren_.read())
            {
                std::snprintf(line, sizeof line, "# push 0x%02x to the native decoder (no extension register written)\n", v & 0xFFu);
                rec_pending_ += line;
                return;
            }
            if (!h_wren_.read() || !(is_param(a) || is_ext(a) || a == PUSH_A)) return;
            std::snprintf(line, sizeof line, "W %08X %08X\n", a, v);
            rec_pending_ += line;
            if (is_param(a)) { rec_param_[(a - PARAM_LO) / 4] = v; rec_param_set_[(a - PARAM_LO) / 4] = true; }
            if ((ext_is_address(a) || param_is_address(a)) && v > rec_max_addr_ && v < staging_base_) rec_max_addr_ = v;
            if (a != PUSH_A) return;
            const bool changed = !rec_hash_valid_ || image_hash() != rec_hash_;
            if (rec_seg_ < 0 || (idle_prev_ && changed))
            {
                if (rec_mmio_) std::fclose(rec_mmio_);
                rec_seg_++;
                make_dir(seg_path(""));
                write_image(seg_path("dram_init.bin"));
                write_image(seg_path("dram_golden.bin"));
                rec_init_bytes_ = rec_extent_;
                rec_mmio_ = std::fopen(seg_path("mmio.txt").c_str(), "w");
                if (!rec_mmio_ && !rec_open_failed_)
                {
                    std::fprintf(stderr, "[core_rtl] WARNING: SAURIA_CORE_RTL_RECORD: cannot write %s (the directory above the last "
                                 "path element must exist); nothing is recorded\n", seg_path("mmio.txt").c_str());
                    rec_open_failed_ = true;
                }
                if (!rec_csv_)
                {
                    rec_csv_ = std::fopen((rec_dir_ + "/record.csv").c_str(), "w");
                    if (rec_csv_) std::fprintf(rec_csv_, "event,instruction,segment_or_opcode,cycles_or_error,state\n");
                }
                if (rec_mmio_)
                {
                    std::fprintf(rec_mmio_, "# recorded by core_rtl/npu_top.h (SAURIA_CORE_RTL_RECORD), segment %d, image %zu bytes\n"
                                 "# parameter registers held at the start of the segment\n", rec_seg_, rec_extent_);
                    for (uint32_t r = 0; r < kParamRegs; r++)
                        if (rec_param_set_[r]) std::fprintf(rec_mmio_, "W %08X %08X\n", PARAM_LO + 4 * r, rec_param_[r]);
                }
            }
            else if (!idle_prev_ && rec_mmio_)
                std::fprintf(rec_mmio_, "# the next instruction was pushed while an earlier one was queued or running\n");
            if (rec_mmio_) { std::fputs(rec_pending_.c_str(), rec_mmio_); std::fflush(rec_mmio_); }
            rec_pending_.clear();
        }
        // ---- performance report (SAURIA_CORE_RTL_REPORT) ---------------------------------------------------------------
        struct RepDesc { uint32_t op{0}, par[kParamRegs]{}, ext[kExtRegs]{}; bool xs[kExtRegs]{}; };
        struct RepSnap
        {
            uint64_t cycles{0}, tiles{0}, passes{0}, busy{0}, real{0}, dma{0}, obp{0}, cfg{0}, elem{0}, rce{0}, rd{0}, wr{0};
        };
        RepSnap rep_snap() const
        {
            RepSnap r;
            r.cycles = rtl->st.cycles; r.tiles = rtl->st.tiles; r.passes = rtl->st.core_passes + rtl->st.rce_core_passes;
            r.busy = rtl->st.core_busy; r.real = rtl->st.real_macs; r.dma = rtl->st.dma_cycles; r.obp = rtl->st.obp_cycles;
            r.cfg = rtl->st.cfg_cycles; r.elem = rtl->st.elem_cycles; r.rce = rtl->st.rce_cycles;
            r.rd = rtl->dma_stats().read_bytes; r.wr = rtl->dma_stats().write_bytes;
            return r;
        }
        void rep_open(const char *path)
        {
            rep_path_ = path;
            rep_csv_ = std::fopen(path, "w");
            if (!rep_csv_)
            {
                std::fprintf(stderr, "[core_rtl] WARNING: SAURIA_CORE_RTL_REPORT: cannot write %s; no report\n", path);
                return;
            }
            std::fprintf(rep_csv_, "instruction,operation,in_c,in_h,in_w,out_c,out_h,out_w,kh,kw,stride,pad,tile_cout,tile_h,tile_w,tile_cin,"
                                   "elements,cycles,cycles_so_far,tiles,core_passes,core_busy_cycles,real_macs,pe_utilization_percent,"
                                   "dma_wait_cycles,epilogue_cycles,epilogue_config_cycles,elem_wise_cycles,rce_cycles,ddr_read_bytes,"
                                   "ddr_write_bytes,state,pad_t,pad_l,pad_b,pad_r,pad_value,dilation\n");
            std::fflush(rep_csv_);
        }
        // A host write that reaches HasNpuTop: keep the registers; at the push, check the addresses of the instruction and
        // queue what it is for the report.
        void rep_write(uint32_t a, uint32_t v)
        {
            if (is_param(a)) rep_par_[(a - PARAM_LO) / 4] = v;
            else if (is_ext(a)) { rep_ext_[(a - EXT_LO) / 4] = v; rep_ext_set_[(a - EXT_LO) / 4] = true; }
            else if (a == PUSH_A)
            {
                RepDesc d;
                d.op = v & 0xFFu;
                std::memcpy(d.par, rep_par_, sizeof rep_par_);
                std::memcpy(d.ext, rep_ext_, sizeof rep_ext_);
                std::memcpy(d.xs, rep_ext_set_, sizeof rep_ext_set_);
                // A wrapper may have shrunk the shared DRAM vector (for example cleared it at a reset) below the private
                // staging area of HasNpuTop: restore its size before the instruction runs. Only while nothing runs.
                if (dram_ && idle_prev_) rtl->set_staging_base(staging_base_);
                if (warn_) bounds_check(d);
                if (rep_csv_) rep_q_.push_back(d);
                std::memset(rep_ext_, 0, sizeof rep_ext_);
                std::memset(rep_ext_set_, 0, sizeof rep_ext_set_);
            }
        }
        // Every region the instruction reads or writes must end inside the DRAM image area, which ends where the staging
        // area of HasNpuTop begins. The sizes follow the registers as HasNpuTop reads them.
        void bounds_check(const RepDesc &d)
        {
            auto P = [&](uint32_t addr) { return d.par[(addr - PARAM_LO) / 4]; };
            auto E = [&](uint32_t addr) { return d.ext[(addr - EXT_LO) / 4]; };
            auto S = [&](uint32_t addr) { return d.xs[(addr - EXT_LO) / 4]; };
            struct Region { const char *what; uint64_t addr, bytes; };
            Region r[10];
            int n = 0;
            auto add = [&](const char *what, uint64_t addr, uint64_t bytes) { if (bytes && n < 10) r[n++] = Region{what, addr, bytes}; };
            const uint32_t mode = (P(0x40000454) & 0xFFFF0000u) ? (P(0x40000454) >> 24) & 0xFFu : P(0x40000454);
            if (d.op == 0x12 && S(0x4000046C))
            {
                const uint64_t in_c = E(0x4000046C), in_h = E(0x40000470), in_w = E(0x40000474), out_c = E(0x40000478), out_h = E(0x4000047C), out_w = E(0x40000480);
                const uint64_t kh = P(0x4000041C) ? P(0x4000041C) : 1, kw = P(0x40000420) ? P(0x40000420) : 1, K = in_c * kh * kw, tc = E(0x40000484);
                // weights: one block per output-channel range; with PAD_TAIL (FLAGS bit 0) the last range is a whole one
                const uint64_t wch = ((E(0x400004A0) & 1u) && tc) ? (out_c + tc - 1) / tc * tc : out_c;
                add("the input tensor (IN_ADDR)", P(0x40000400), in_c * in_h * in_w);
                add("the weights (W_ADDR)", P(0x40000404), wch * K);
                add("the output tensor (OUT_ADDR)", P(0x40000408), out_c * out_h * out_w);
                add("the bias array (BIAS_ADDR)", P(0x4000040C), 4 * out_c);
                if (S(0x40000490)) { add("the scale array (SCALE_ADDR)", E(0x40000490), 4 * out_c); add("the shift array (SHIFT_ADDR)", E(0x40000494), 4 * out_c); }
                if (P(0x4000042C) == 2 || P(0x4000042C) == 3) add("the activation table (LUT_ADDR)", E(0x40000498), 256);
                if (P(0x40000430)) add("the skip tensor (SKIP_ADDR)", P(0x40000434), out_c * out_h * out_w);
                // One tile against one buffer of each SRAM (79 KB input window, 81 KB weights, 24,576 partial sums). The
                // model runs the instruction all the same; the hardware could not.
                const uint64_t th = E(0x40000488), tw = E(0x4000048C), ct = (S(0x400004D4) && E(0x400004D4)) ? E(0x400004D4) : in_c;
                const uint64_t sd = P(0x40000424) ? P(0x40000424) : 1;
                const uint64_t dl = (S(0x400004FC) && E(0x400004FC) && E(0x400004FC) < 64) ? E(0x400004FC) : 1;   // DILATION
                const uint64_t ekh = (kh - 1) * dl + 1, ekw = (kw - 1) * dl + 1;                                  // effective kernel
                if (tc && th && tw && out_h && out_w)
                {
                    const uint64_t h = th < out_h ? th : out_h, w = tw < out_w ? tw : out_w;
                    const uint64_t a_bytes = ct * ((h - 1) * sd + ekh) * ((w - 1) * sd + ekw), b_bytes = tc * ct * kh * kw, c_el = tc * h * w;
                    if (a_bytes > 80896 || b_bytes > 82944 || c_el > 24576)
                    {
                        std::fprintf(stderr, "[core_rtl] WARNING: push %llu (opcode 0x12): a tile of TILE_COUT %llu x TILE_H %llu x TILE_W %llu"
                                     " (TILE_CIN %llu) does not fit the SRAMs of the hardware (over:%s%s%s): input window %llu bytes (limit 80896),"
                                     " weights %llu bytes (limit 82944), partial sums %llu (limit 24576). The model runs it all the same;"
                                     " results may be wrong\n",
                                     static_cast<unsigned long long>(pushes_ + 1), static_cast<unsigned long long>(tc),
                                     static_cast<unsigned long long>(th), static_cast<unsigned long long>(tw), static_cast<unsigned long long>(ct),
                                     a_bytes > 80896 ? " SRAM-A" : "", b_bytes > 82944 ? " SRAM-B" : "", c_el > 24576 ? " SRAM-C" : "",
                                     static_cast<unsigned long long>(a_bytes), static_cast<unsigned long long>(b_bytes),
                                     static_cast<unsigned long long>(c_el));
                        rep_tile_++;
                        std::fflush(stderr);
                    }
                }
            }
            else if (d.op == 0x15 && mode == 0)
            {
                add("operand A (A_ADDR)", P(0x40000444), P(0x40000450));
                add("operand B (B_ADDR)", P(0x40000448), P(0x40000450));
                add("the output tensor (OUT_ADDR)", P(0x40000408), P(0x40000450));
            }
            else if (d.op == 0x15)
            {
                const uint64_t c = E(0x4000046C), h = E(0x40000470), w = E(0x40000474), k = E(0x400004C8), pd = E(0x400004CC), st = P(0x40000424) ? P(0x40000424) : 1;
                add("the input tensor (A_ADDR)", P(0x40000444), c * h * w);
                if (k && h + 2 * pd >= k && w + 2 * pd >= k) add("the output tensor (OUT_ADDR)", P(0x40000408), c * ((h + 2 * pd - k) / st + 1) * ((w + 2 * pd - k) / st + 1));
            }
            else if (d.op == 0x13)
            {
                const uint64_t L = P(0x40000450), D = P(0x40000458), nq = E(0x400004DC) ? E(0x400004DC) : L;
                add("the query tensor (A_ADDR)", P(0x40000444), nq * D);
                add("the key tensor (B_ADDR)", P(0x40000448), L * D);
                add("the value tensor (V_ADDR)", P(0x4000044C), L * D);
                add("the output tensor (OUT_ADDR)", P(0x40000408), nq * D);
                add("the parameter block (PARAM_ADDR)", E(0x400004E0), 4);
                if (S(0x400004E4)) add("the mask (MASK_ADDR)", E(0x400004E4), nq * L);
            }
            else if (d.op == 0x14)
            {
                const uint64_t rows = E(0x400004DC), H = P(0x40000450);
                add("the input tensor (IN_ADDR)", P(0x40000400), rows * H);
                add("the output tensor (OUT_ADDR)", P(0x40000408), rows * H);
                add("the parameter block (PARAM_ADDR)", E(0x400004E0), 4);
            }
            const uint64_t lim = staging_base_;
            bool any = false;
            for (int k = 0; k < n; k++)
            {
                if (r[k].addr + r[k].bytes <= lim) continue;
                any = true;
                std::fprintf(stderr, "[core_rtl] WARNING: push %llu (opcode 0x%02x): %s at 0x%llx, %llu bytes, ends beyond the DRAM image area "
                             "of 0x%llx bytes%s. The model does not check addresses: wrong data or a crash of the simulation follows\n",
                             static_cast<unsigned long long>(pushes_ + 1), d.op, r[k].what, static_cast<unsigned long long>(r[k].addr),
                             static_cast<unsigned long long>(r[k].bytes), static_cast<unsigned long long>(lim),
                             r[k].addr >= dram_base_ ? " (the address looks like a bus address that was not converted to an image offset)" : "");
            }
            if (any) { rep_oob_++; std::fflush(stderr); }
        }
        // One line when the count of retired instructions (register RETIRED) has grown.
        void rep_tick()
        {
            const uint32_t r = rtl->mmio.read(RETIRED);
            if (r == rep_retired_) return;
            if (r < rep_retired_) { rep_retired_ = r; return; }   // soft reset
            rep_retired_ = r;
            const RepSnap s = rep_snap();
            RepDesc d;
            if (!rep_q_.empty()) { d = rep_q_.front(); rep_q_.pop_front(); }
            auto P = [&](uint32_t addr) { return d.par[(addr - PARAM_LO) / 4]; };
            auto E = [&](uint32_t addr) { return d.ext[(addr - EXT_LO) / 4]; };
            auto XS = [&](uint32_t addr) { return d.xs[(addr - EXT_LO) / 4]; };
            const uint32_t mode = (P(0x40000454) & 0xFFFF0000u) ? (P(0x40000454) >> 24) & 0xFFu : P(0x40000454);
            const char *name = d.op == 0x12 ? "GEMM_FUSED" : d.op == 0x13 ? "FUSED_ATTN" : d.op == 0x14 ? "LAYERNORM" :
                               d.op != 0x15 ? "?" : mode == 0 ? "ELEM_WISE_ADD" : mode == 1 ? "ELEM_WISE_MAX_POOL" :
                               mode == 5 ? "ELEM_WISE_AVG_POOL" : "ELEM_WISE";
            uint32_t g[14] = {0};   // in_c in_h in_w out_c out_h out_w kh kw stride pad tile_cout tile_h tile_w tile_cin
            uint64_t elements = 0;
            if (d.op == 0x12)
            {
                const bool x = E(0x4000046C) != 0;
                g[0] = x ? E(0x4000046C) : P(0x40000414); g[1] = x ? E(0x40000470) : 1; g[2] = x ? E(0x40000474) : P(0x40000410);
                g[3] = x ? E(0x40000478) : P(0x40000418); g[4] = x ? E(0x4000047C) : 1; g[5] = x ? E(0x40000480) : P(0x40000410);
                g[6] = x ? P(0x4000041C) : 1; g[7] = x ? P(0x40000420) : 1; g[8] = x ? P(0x40000424) : 1; g[9] = x ? P(0x40000428) : 0;
                g[10] = E(0x40000484); g[11] = E(0x40000488); g[12] = E(0x4000048C); g[13] = E(0x400004D4);
                elements = uint64_t(g[3]) * g[4] * g[5];
            }
            else if (d.op == 0x15 && mode == 0) elements = P(0x40000450);
            else if (d.op == 0x15)
            {
                const uint32_t k = E(0x400004C8), pd = E(0x400004CC), st = P(0x40000424) ? P(0x40000424) : 1;
                g[0] = g[3] = E(0x4000046C); g[1] = E(0x40000470); g[2] = E(0x40000474); g[6] = g[7] = k; g[8] = st; g[9] = pd;
                if (k && g[1] + 2 * pd >= k && g[2] + 2 * pd >= k) { g[4] = (g[1] + 2 * pd - k) / st + 1; g[5] = (g[2] + 2 * pd - k) / st + 1; }
                elements = uint64_t(g[3]) * g[4] * g[5];
            }
            else if (d.op == 0x13) { g[4] = E(0x400004DC) ? E(0x400004DC) : P(0x40000450); g[5] = P(0x40000458); g[2] = P(0x40000450); elements = uint64_t(g[4]) * g[5]; }
            else if (d.op == 0x14) { g[4] = E(0x400004DC); g[5] = P(0x40000450); elements = uint64_t(g[4]) * g[5]; }
            // padding per side, padding value and dilation as the instruction uses them (last columns of the row): GEMM_FUSED
            // takes PAD_T / L / B / R when any of them is written, else PAD; pooling uses its POOL_P on all sides
            uint32_t pads[4] = {g[9], g[9], g[9], g[9]}, dil = 1;
            int pad_value = 0;
            if (d.op == 0x12 && E(0x4000046C) != 0)
            {
                if (XS(0x400004EC) || XS(0x400004F0) || XS(0x400004F4) || XS(0x400004F8))
                { pads[0] = E(0x400004EC); pads[1] = E(0x400004F0); pads[2] = E(0x400004F4); pads[3] = E(0x400004F8); }
                pad_value = int(static_cast<int8_t>(E(0x400004E8) & 0xFFu));
                dil = (E(0x400004FC) && !(g[6] == 1 && g[7] == 1)) ? E(0x400004FC) : 1;
            }
            const uint64_t cyc = s.cycles - rep_s_.cycles, busy = s.busy - rep_s_.busy, real = s.real - rep_s_.real;
            std::fprintf(rep_csv_, "%u,%s", r, name);
            for (uint32_t v : g) std::fprintf(rep_csv_, ",%u", v);
            std::fprintf(rep_csv_, ",%llu,%llu,%llu,%llu,%llu,%llu,%llu,%.2f,%llu,%llu,%llu,%llu,%llu,%llu,%llu,%s",
                         static_cast<unsigned long long>(elements), static_cast<unsigned long long>(cyc),
                         static_cast<unsigned long long>(s.cycles - rep_s0_.cycles), static_cast<unsigned long long>(s.tiles - rep_s_.tiles),
                         static_cast<unsigned long long>(s.passes - rep_s_.passes), static_cast<unsigned long long>(busy),
                         static_cast<unsigned long long>(real), busy ? 100.0 * double(real) / (double(busy) * double(X_DIM) * double(Y_DIM)) : 0.0,
                         static_cast<unsigned long long>(s.dma - rep_s_.dma), static_cast<unsigned long long>(s.obp - rep_s_.obp),
                         static_cast<unsigned long long>(s.cfg - rep_s_.cfg), static_cast<unsigned long long>(s.elem - rep_s_.elem),
                         static_cast<unsigned long long>(s.rce - rep_s_.rce), static_cast<unsigned long long>(s.rd - rep_s_.rd),
                         static_cast<unsigned long long>(s.wr - rep_s_.wr),
                         rep_bad_ ? "errors" : "ok");
            std::fprintf(rep_csv_, ",%u,%u,%u,%u,%d,%u\n", pads[0], pads[1], pads[2], pads[3], pad_value, dil);
            std::fflush(rep_csv_);
            const int k = d.op == 0x12 ? 0 : d.op == 0x15 ? 1 : d.op == 0x13 ? 2 : d.op == 0x14 ? 3 : 4;
            rep_op_n_[k]++;
            rep_op_cyc_[k] += cyc;
            rep_rows_++;
            if (rep_bad_) rep_errors_++;
            rep_bad_ = false;
            rep_s_ = s;
            rep_summary();
        }
        void rep_summary() const
        {
            std::FILE *f = std::fopen((rep_path_ + ".summary.txt").c_str(), "w");
            if (!f) return;
            const RepSnap s = rep_snap();
            const uint64_t cyc = rep_s_.cycles - rep_s0_.cycles, busy = rep_s_.busy - rep_s0_.busy, real = rep_s_.real - rep_s0_.real;
            const double per_ns = period_.to_seconds() * 1e9, sec = double(cyc) * period_.to_seconds();
            auto pct = [&](uint64_t v) { return cyc ? 100.0 * double(v) / double(cyc) : 0.0; };
            static const char *opn[5] = {"GEMM_FUSED", "ELEM_WISE", "FUSED_ATTN", "LAYERNORM", "other"};
            std::fprintf(f, "performance of the instructions HasNpuTop retired (SAURIA_CORE_RTL_REPORT); steps of the CPU and the copies of a "
                            "wrapper are not included\n");
            std::fprintf(f, "instructions_retired        %llu\n", static_cast<unsigned long long>(rep_rows_));
            std::fprintf(f, "pushes_refused              %llu\n", static_cast<unsigned long long>(rep_refused_));
            std::fprintf(f, "instructions_with_errors    %llu\n", static_cast<unsigned long long>(rep_errors_));
            std::fprintf(f, "pushes_beyond_image         %llu\n", static_cast<unsigned long long>(rep_oob_));
            std::fprintf(f, "pushes_tile_above_sram      %llu\n", static_cast<unsigned long long>(rep_tile_));
            std::fprintf(f, "instructions_in_flight      %llu\n", static_cast<unsigned long long>(rep_q_.size()));
            std::fprintf(f, "cycles                      %llu\n", static_cast<unsigned long long>(cyc));
            std::fprintf(f, "clock_period_ns             %.4f\n", per_ns);
            std::fprintf(f, "time_ms                     %.4f\n", sec * 1e3);
            std::fprintf(f, "frames_per_second           %.4f   (one run of these instructions per frame)\n", sec > 0.0 ? 1.0 / sec : 0.0);
            std::fprintf(f, "pe_utilization_percent      %.2f   (real MACs %llu / core busy cycles %llu x %d PEs)\n",
                         busy ? 100.0 * double(real) / (double(busy) * double(X_DIM) * double(Y_DIM)) : 0.0,
                         static_cast<unsigned long long>(real), static_cast<unsigned long long>(busy), X_DIM * Y_DIM);
            std::fprintf(f, "core_busy_percent           %.2f\n", pct(busy));
            std::fprintf(f, "dma_wait_percent            %.2f   (%llu cycles)\n", pct(rep_s_.dma - rep_s0_.dma),
                         static_cast<unsigned long long>(rep_s_.dma - rep_s0_.dma));
            std::fprintf(f, "epilogue_percent            %.2f   (%llu cycles, configuration %llu)\n", pct(rep_s_.obp - rep_s0_.obp),
                         static_cast<unsigned long long>(rep_s_.obp - rep_s0_.obp), static_cast<unsigned long long>(rep_s_.cfg - rep_s0_.cfg));
            std::fprintf(f, "tiles                       %llu\n", static_cast<unsigned long long>(rep_s_.tiles - rep_s0_.tiles));
            std::fprintf(f, "core_passes                 %llu\n", static_cast<unsigned long long>(rep_s_.passes - rep_s0_.passes));
            std::fprintf(f, "ddr_read_bytes              %llu\n", static_cast<unsigned long long>(rep_s_.rd - rep_s0_.rd));
            std::fprintf(f, "ddr_write_bytes             %llu\n", static_cast<unsigned long long>(rep_s_.wr - rep_s0_.wr));
            for (int k = 0; k < 5; k++)
                if (rep_op_n_[k])
                    std::fprintf(f, "%-27s %llu instructions, %llu cycles, %.2f %%\n", opn[k], static_cast<unsigned long long>(rep_op_n_[k]),
                                 static_cast<unsigned long long>(rep_op_cyc_[k]), pct(rep_op_cyc_[k]));
            (void)s;
            std::fclose(f);
        }

        struct RtlSnap
        {
            uint64_t instr{0}, cycles{0}, dma{0}, obp{0}, rce{0}, elem{0}, rd{0}, wr{0};
            uint64_t busy{0}, real{0}, macs{0}, rd_cyc{0}, wr_cyc{0};
        };
        RtlSnap rtl_snap() const
        {
            RtlSnap s;
            s.instr = rtl->st.instr; s.cycles = rtl->st.cycles; s.dma = rtl->st.dma_cycles; s.obp = rtl->st.obp_cycles;
            s.rce = rtl->st.rce_cycles; s.elem = rtl->st.elem_cycles;
            s.rd = rtl->dma_stats().read_bytes; s.wr = rtl->dma_stats().write_bytes;
            s.busy = rtl->st.core_busy; s.real = rtl->st.real_macs; s.macs = rtl->st.macs;
            s.rd_cyc = rtl->dma_stats().read_port_cycles; s.wr_cyc = rtl->dma_stats().write_port_cycles;
            return s;
        }
        void add_rtl_counters()
        {
            const RtlSnap s = rtl_snap();
            if (s.instr == snap_.instr) return;
            on_retire(s.instr, s.cycles - snap_.cycles);
            if (perf_)
            {
                perf_->exec_cycles += s.cycles - snap_.cycles;
                perf_->processing_cycles += s.cycles - snap_.cycles;
                perf_->dma_engine_cycles += s.dma - snap_.dma;
                perf_->obp_cycles += s.obp - snap_.obp;
                perf_->reduction_engine_cycles += s.rce - snap_.rce;
                perf_->pooling_engine_cycles += s.elem - snap_.elem;
                perf_->ddr_read_bytes += s.rd - snap_.rd;
                perf_->ddr_write_bytes += s.wr - snap_.wr;
                perf_->dma_read_cycles_raw += s.rd_cyc - snap_.rd_cyc;
                perf_->dma_write_cycles_raw += s.wr_cyc - snap_.wr_cyc;
                perf_->active_pe_cycles += s.real - snap_.real;
                perf_->total_pe_cycles += (s.busy - snap_.busy) * uint64_t(X_DIM) * uint64_t(Y_DIM);
                perf_->sa_cycles += s.busy - snap_.busy;
                perf_->mac_engine_cycles += s.busy - snap_.busy;
                perf_->mac_ops += s.macs - snap_.macs;
            }
            snap_ = s;
        }
