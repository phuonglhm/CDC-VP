// core_rtl/npu_top.h -- drop-in top level for system integration wrappers that runs instruction streams on the
// RTL-accurate core.
//
// A wrapper written for the native top level (../npu_top.h, class sauria::NpuTop) builds unchanged when its model
// root points at this directory: same class name, template parameters, constructor, ports, attach_perf(), set_dram()
// and decoder_inst. Inside, two engines share the host bus:
//   - the native top level (../npu_top.h) for the native configuration registers, the SRAM windows, the OBP / RCE
//     tables, i_start, and for instructions pushed without extension registers (functional decoder, as before);
//   - HasNpuTop (../has/has_npu_top.h: RTL-accurate core, HAS data flow controller, DMA, epilogue and vector unit) for
//     instructions pushed after writing extension registers 0x4000046C..0x40000503 (programs generated by
//     tools/fe/fe_emit_insts.py, tools/fe/fe_vit_full.py).
// Host bus routing:
//   0x40000400..0x40000468  instruction parameters: written to both engines
//   0x4000046C..0x40000503  extension registers: HasNpuTop only; marks the next push for HasNpuTop
//   0x40000310              push, lane A: HasNpuTop when extension registers were written since the previous push
//                           or the opcode is 0x16 (DMA_TENSOR) and HAS_DMA_TENSOR=1,
//                           otherwise the native decoder
//   0x40000318, 0x4000031C  STATUS, RETIRED of HasNpuTop (read and write)
//   everything else         native top level
// decoder_inst reports the instructions of both engines (queue size and busy state), so a wrapper that detects
// completion from the queue size keeps working. o_done / o_deadlock are those of the native top level.
// Performance counters (attach_perf): the native top level counts as before (total_cycles every clock, the other
// fields for instructions of the native decoder). Each HasNpuTop instruction adds, when it retires:
//   exec_cycles, processing_cycles += instruction cycles (RTL-accurate core, modelled DMA and vector unit)
//   dma_engine_cycles += cycles waiting for the DMA      obp_cycles += epilogue cycles
//   reduction_engine_cycles += FUSED_ATTN / LAYERNORM cycles    pooling_engine_cycles += ELEM_WISE cycles
//   ddr_read_bytes, ddr_write_bytes += DMA bytes
//   dma_read_cycles_raw, dma_write_cycles_raw += cycles the DMA read / write port is busy
//   PE utilization of the RTL-accurate core = active_pe_cycles / total_pe_cycles, with
//     active_pe_cycles += real MACs of the instruction (output elements x K; attention products of FUSED_ATTN)
//     total_pe_cycles  += core busy cycles x X_DIM x Y_DIM (busy: start pulse to o_done of every core pass)
//     sa_cycles, mac_engine_cycles += core busy cycles      mac_ops += MACs executed, including tile padding
//   For these instructions active_pe_cycles is the real MAC count, not the count of non-zero operand pairs that the
//   native array reports.
//
// DRAM: set_dram() gives the same byte vector to both engines. HasNpuTop addresses are offsets in that vector. Address
// values of the extension registers at or above dram_base() (default 0x80000000, the start of system RAM in a wrapper
// that stores RAM-relative offsets) are converted to offsets, like the wrapper does for the parameter registers.
// HasNpuTop's private staging area is placed at staging_base() (default 0x10000000), above every RAM offset.
//
// Environment (read at construction):
//   SAURIA_CORE_RTL_PROFILE  recommended (default) | proposals | legacy   -- HasNpuTop run profile
//   SAURIA_CORE_RTL_C_BCAST  1: bias preload by broadcast descriptor (timing only; reproduces the ViT-B/16 reference cycles)
//   SAURIA_CORE_RTL_TRACE    1: one line per executed HasNpuTop instruction on stdout
//   SAURIA_CORE_RTL_WARN     0: no warnings. Default: one line on stderr when HasNpuTop refuses an instruction at the push
//                            (the instruction never runs although a wrapper that watches the queue reports completion),
//                            when an instruction falls back to converted real-valued scales or to a default tiling,
//                            when an instruction retires with an internal error counter raised (output missing or wrong),
//                            and when a tensor, weight block or parameter array of a pushed instruction ends beyond the
//                            DRAM image area (the model does not check addresses: wrong data or a crash would follow).
//                            The last check is made at the push, before the instruction runs
//   SAURIA_CORE_RTL_RECORD   <directory>: record the program that reaches HasNpuTop, in the program-directory format of
//                            tools/has/tb_has_npu_top (mmio.txt, dram_init.bin, dram_golden.bin), as <directory>/segNNN.
//                            A new segment starts at the first instruction and whenever the DRAM image changed between
//                            the end of an instruction and the next push (a step done by the CPU). mmio.txt holds the
//                            register values as HasNpuTop receives them (addresses already converted to DRAM offsets);
//                            dram_init.bin is the image at the first push of the segment; dram_golden.bin is the image
//                            after the last instruction of the segment AS THIS RUN PRODUCED IT (not an independent
//                            reference), rewritten after every instruction; record.csv has one line per instruction.
//                            The image is recorded up to its last non-zero byte and to the highest address written to
//                            an address register (rounded up to 64 KiB). Costs one image write per instruction.
//   SAURIA_CORE_RTL_REPORT   <file>: performance report of the run. <file> is a CSV with one line per instruction that
//                            HasNpuTop retired (what the instruction was, its cycles, tiles, core passes, PE utilization,
//                            the cycles waiting for the DMA / in the epilogue / in the vector unit, bytes on the bus,
//                            ok or errors); <file>.summary.txt holds the totals of the run so far (cycles, frames per
//                            second at the clock that drives the model, PE utilization, shares, refused pushes) and is
//                            rewritten after every instruction, so it is complete however the simulation ends. Steps the
//                            CPU does between instructions and the copies a wrapper makes are not in these numbers.
// None of these options changes results or cycle counts.
//   HAS_*                    knobs of has::Knobs::from_env() (for example HAS_SP_PRESET=gvu68k), as for tools/has/tb_has_npu_top
